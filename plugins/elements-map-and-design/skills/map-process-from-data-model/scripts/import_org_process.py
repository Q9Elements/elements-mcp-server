#!/usr/bin/env python3
"""Take over a map Elements' org-to-process generated as one level of this run.

Usage:
  import_org_process.py --process saved-get_process_map.json --brief briefs/<level>.json --inventory inventory.json [--out levels/<level>.json]

On route metadata, the process of one record type is generated first with generate_process_map
(source org_object, the object, the record type and the lifecycle field). It comes back as a map of its
own; get_process_map reads it as activities and transitions. This script turns that read into the level
outline the brief asks for, so the build draws it as a child level of this map (the generated map
stays as it is):

- each activity becomes a step: its text the box text, its resources the roles (a name that is an object
  in the inventory becomes a use; "Salesforce" and other system names become system roles after the
  people). A box with no person gets --default-role, and a box with no object the brief's object;
- each transition between activities becomes a line with its label;
- a transition with no start becomes a start; the brief's parent inputs are copied onto the first one, so
  the drill-down matches its box, and the generated label is kept in the step's evidence;
- a transition with no end becomes an end; the brief's parent outputs go on the first one in the same way.

The outline is marked "source": "org-to-process": the lifecycle checks of a writer's outline (one step
per value) do not apply to it, since the generator decides the steps from the org's automation.
Standard library only; Python 3.8 or later.
"""

import argparse
import sys
from pathlib import Path

import common
from common import SetupError

SYSTEMS = {"salesforce", "system", "automation", "flow"}  # resource names drawn as system roles


def step_id(activity, taken):
    base = f"a{activity.get('number') or len(taken) + 1}"
    sid, n = base, 2
    while sid in taken:
        sid, n = f"{base}-{n}", n + 1
    taken.add(sid)
    return sid


def convert(process, brief, inv, default_role="Process owner"):
    objects = {o["apiName"]: o for o in inv.get("objects", [])}
    by_name = {common.norm(o["name"]): a for a, o in objects.items()}
    by_name.update({common.norm(a): a for a in objects})
    main_object = (brief.get("object") or {}).get("apiName")
    taken, ids, steps = set(), {}, []
    for act in process.get("activities", []):
        sid = step_id(act, taken)
        ids[act["id"]] = sid
        roles, uses = [], []
        for res in act.get("resources", []):
            name = (res.get("name") or "").strip()
            if not name:
                continue
            if common.norm(name) in by_name:
                uses.append(by_name[common.norm(name)])
            elif common.norm(name) in SYSTEMS:
                roles.append({"name": name, "kind": "system"})
            else:
                roles.append({"name": name})
        if not any(r.get("kind", "human") == "human" for r in roles):
            roles.append({"name": default_role})  # every box has a person doing it; the owner confirms who
        roles.sort(key=lambda r: 0 if r.get("kind", "human") == "human" else 1)
        if not uses and main_object:
            uses.append(main_object)  # every box shows the record it works on
        text = act.get("text") or f"Step {act.get('number')}"
        steps.append({"id": sid, "name": text[:100], "roles": roles, "uses": common.dedupe(uses),
                      "what": f"{text}. Generated by Elements' org-to-process from the org's record types, lifecycle field and automation.",
                      "why": "Taken over as generated; have the process owner confirm it.", "next": []})
    by_step = {s["id"]: s for s in steps}
    starts, ends = [], []
    for tr in process.get("transitions", []):
        src, dst, label = ids.get(tr.get("fromActivityId")), ids.get(tr.get("toActivityId")), (tr.get("label") or "").strip()
        if src and dst:
            by_step[src]["next"].append({"to": dst, "outcome": label or f"{by_step[src]['name']} done"})
        elif dst:
            starts.append({"to": dst, "trigger": label or "Process started"})
        elif src:
            ends.append({"from": src, "outcome": label or f"{by_step[src]['name']} done"})
    if not starts and steps:
        starts.append({"to": steps[0]["id"], "trigger": "Process started"})
    parent = brief.get("parent") or {}
    if parent.get("inputs") and starts:
        first = starts[0]
        by_step[first["to"]].setdefault("evidence", []).append(f"Generated start: {first['trigger']}")
        starts = [{"to": first["to"], "trigger": label} for label in parent["inputs"]] + starts[1:]
    if parent.get("outputs"):
        if ends:
            first = ends[0]
            by_step[first["from"]].setdefault("evidence", []).append(f"Generated end: {first['outcome']}")
            ends = [{"from": first["from"], "outcome": label} for label in parent["outputs"]] + ends[1:]
        elif steps:
            ends = [{"from": steps[-1]["id"], "outcome": label} for label in parent["outputs"]]
    for step in steps:
        if not step["next"]:
            del step["next"]
        if not step["uses"]:
            del step["uses"]
    outline = {"schemaVersion": "1.0", "level": brief["level"], "source": "org-to-process", "steps": steps, "starts": starts}
    if ends:
        outline["ends"] = ends
    name = (process.get("metadata") or {}).get("name")
    gap = {"note": f"This level was generated by Elements' org-to-process{' (' + name + ')' if name else ''} and taken over as it is; "
                   "its steps follow the org's automation rather than one box per status value, so its lines set no status value."}
    if main_object:
        gap["about"] = main_object  # the coverage check then warns, rather than fails, on the values no line sets
    outline["gaps"] = [gap]
    return outline


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")
    parser = argparse.ArgumentParser(description="Take over an org-to-process map as one level of this run.")
    parser.add_argument("--process", type=Path, required=True, help="saved get_process_map result")
    parser.add_argument("--brief", type=Path, required=True)
    parser.add_argument("--inventory", type=Path, required=True)
    parser.add_argument("--out", type=Path, help="the brief's outlinePath when left out")
    parser.add_argument("--default-role", default="Process owner", help="the person on a box the generator gave no person (default: Process owner)")
    args = parser.parse_args(argv)
    try:
        process = common.load_json(args.process, "process map")
        brief = common.load_json(args.brief, "brief")
        inv = common.load_json(args.inventory, "inventory")
        if process.get("status") != "complete" or process.get("empty"):
            raise SetupError("the process map is not complete or is empty; poll get_process_map until it is complete, or fall back to the per-value writer")
        outline = convert(process, brief, inv, args.default_role)
    except SetupError as exc:
        print(f"SETUP {exc}", file=sys.stderr)
        return 2
    errors = common.process_levels.shape_errors(outline, common.OUTLINE_SCHEMA) or common.outline_errors(outline)
    for line in errors:
        print(f"ERROR {line}")
    if errors:
        return 1
    out = args.out or Path(brief["outlinePath"])
    common.write_json(out, outline)
    print(f"PASS: {len(outline['steps'])} step(s), {len(outline['starts'])} start(s), {len(outline.get('ends', []))} end(s) written to {out}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
