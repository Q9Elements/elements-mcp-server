        if not remaining_members:
            continue
        raw_units.append(remaining_members)
        if quarantined_members:
            reasons = [
                f"cycle member {name} is quarantined under {row['rule']}"
                for name in sorted(quarantined_members)
                for row in quarantine_rows
                if row["qualifiedName"] == name
            ]
