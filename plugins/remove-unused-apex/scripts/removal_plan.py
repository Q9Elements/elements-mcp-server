    def orphaned_survivors(members: list[str]) -> list[str]:
        member_set = set(members)
        result = []
        for survivor, row in catalog_by_name.items():
            if survivor in placed_removals or row.get("kind") != "class":
                continue
            callers = {
                source for source in incoming.get(survivor, set())
                if source in catalog_by_name
                and catalog_by_name[source].get("kind") in {"class", "trigger"}
                and not parse_bool(
                    catalog_by_name[source]["isTestClass"],
                    field=f"{source} isTestClass",
                )
            }
            if callers and callers <= placed_removals and callers & member_set:
                result.append(survivor)
