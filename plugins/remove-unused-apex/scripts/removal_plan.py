    # Consumers precede providers; among currently-ready SCCs, choose the biggest first.
    unit_for = {member: index for index, unit in enumerate(units) for member in unit["members"]}
    unit_graph: dict[int, set[int]] = {index: set() for index in range(len(units))}
    indegree = {index: 0 for index in range(len(units))}
    for source, target in pairs:
        left, right = unit_for.get(source), unit_for.get(target)
        if left is not None and right is not None and left != right and right not in unit_graph[left]:
            unit_graph[left].add(right)
            indegree[right] += 1
    ready = [
        (-int(units[index]["countedCharacters"]), str(units[index]["label"]).casefold(), index)
        for index, degree in indegree.items() if degree == 0
    ]
    heapq.heapify(ready)
    ordered_units: list[dict[str, object]] = []
    while ready:
        _, _, index = heapq.heappop(ready)
        ordered_units.append(units[index])
        for target in sorted(unit_graph[index]):
            indegree[target] -= 1
            if indegree[target] == 0:
                heapq.heappush(ready, (
                    -int(units[target]["countedCharacters"]),
                    str(units[target]["label"]).casefold(),
                    target,
                ))

