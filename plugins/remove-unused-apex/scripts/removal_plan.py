def write_metadata_manifest(
    path: Path, members_by_type: dict[str, set[str]], *, version: str
) -> None:
    """Write one Salesforce Metadata API package manifest."""
    type_blocks = []
    for metadata_type, members in sorted(members_by_type.items()):
        if not members:
            continue
        member_lines = "\n".join(
            f"        <members>{escape(member)}</members>"
            for member in sorted(members)
        )
        type_blocks.append(
            f"    <types>\n{member_lines}\n"
            f"        <name>{escape(metadata_type)}</name>\n"
            "    </types>"
        )
    body = "\n".join(type_blocks)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<Package xmlns="http://soap.sforce.com/2006/04/metadata">\n'
        f"{body}\n"
        f"    <version>{escape(version)}</version>\n"
        "</Package>\n",
        encoding="utf-8",
    )


def metadata_api_type(display_type: str) -> str:
    """Map dependency display types to Metadata API manifest type names."""
    return "".join(display_type.split())


def render_blind_spot_value(value: object) -> str:
    if value is None:
        return "none"
    if isinstance(value, list):
        return ", ".join(render_blind_spot_value(item) for item in value) or "none"
    if isinstance(value, dict):
        return ", ".join(
            f"{key}: {render_blind_spot_value(nested)}"
            for key, nested in sorted(value.items())
        ) or "none"
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def targeted_string_holder_result(
    name: str,
    rows: list[dict[str, str]],
    outside_holders: list[str],
    blocked_members: set[str],
    catalog_kinds: dict[str, str],
) -> str:
    test_holders = sorted({
        row["holderName"] for row in rows
        if parse_bool(row["holderIsTest"], field="holderIsTest")
        and row["holderName"]
    })
    blocked_set: set[str] = set()
    unblocked_set: set[str] = set()
    for row in rows:
        holder = row.get("holderName", "").strip()
        if holder not in outside_holders:
            continue
        if parse_bool(row.get("holderIsTest", ""), field="holderIsTest"):
            continue
        member_row = {
            "qualifiedName": holder,
            "holderName": holder,
            "holderType": row.get("holderType", ""),
        }
        if holder in blocked_members and is_self_match(member_row, catalog_kinds):
            blocked_set.add(holder)
        else:
            unblocked_set.add(holder)
    blocked_holders = sorted(blocked_set)
    if blocked_holders and not unblocked_set:
        result = (
            f"Targeted string search for {name}: "
            + "; ".join(
                f"held by {holder}, which stays; see its blocked reason"
                for holder in blocked_holders
            )
        )
    elif outside_holders:
        result = (
            f"Targeted string search for {name}: non-test holders outside the "
            f"removal set: {', '.join(outside_holders)}"
        )
    else:
        result = (
            f"Targeted string search for {name}: no non-test holders outside "
            "the removal set"
        )
    if test_holders:
        result += f"; test holders are exempt: {', '.join(test_holders)}"
    return result + "."


def plan_validation_results(
    tranches: list[dict[str, object]],
    graph: dict[str, set[str]],
    catalog_by_name: dict[str, dict[str, str]],
    capacity_totals: dict[str, object],
    q06_targets: set[str] | None = None,
) -> list[dict[str, object]]:
    """Compute order, survivor-reference, test, and capacity invariants."""
    flattened_units = [
        unit
        for tranche in tranches
        for unit in tranche.get("units", [])
        if isinstance(unit, dict)
    ]
    position = {
        str(member): index
        for index, unit in enumerate(flattened_units)
        for member in unit.get("members", [])
    }
    order_counterexamples = [
        {"consumer": source, "provider": target}
        for source, targets in graph.items()
        for target in targets
        if source in position and target in position
        and position[source] > position[target]
    ]

    attached = [
        str(test)
        for unit in flattened_units
        for test in unit.get("tests", [])
    ]
    attached_set = set(attached)
    removed = set(position)
    test_counterexamples: list[dict[str, object]] = []
    for test in sorted(attached_set):
        count = attached.count(test)
        if count != 1:
            test_counterexamples.append({"test": test, "placements": count})
        outside = {
            target
            for target in graph.get(test, set())
            if target in catalog_by_name
            and target not in attached_set
            and target not in removed
        }
        if outside:
            test_counterexamples.append({
                "test": test,
                "reachesOutsideRemovedUnits": sorted(outside),
            })

    precursor_targets: dict[str, set[str]] = defaultdict(set)
    for unit in flattened_units:
        for rewrite in unit.get("precursorRewrites", []):
            if not isinstance(rewrite, dict):
                continue
            survivor = str(rewrite.get("class", ""))
            if rewrite.get("kind") == "test-edit" and survivor:
                precursor_targets[survivor].update(
                    str(name) for name in rewrite.get("removeReferencesTo", [])
                )
    q06_targets = q06_targets or set()
    survivor_counterexamples: list[dict[str, object]] = []
    for survivor, row in sorted(catalog_by_name.items()):
        if survivor in removed or survivor in attached_set:
            continue
        references_removed = graph.get(survivor, set()) & removed
        if not references_removed:
            continue
        is_test = str(row.get("isTestClass", "")).strip().casefold() == "true"
        covered = precursor_targets.get(survivor, set()) if is_test else q06_targets
        missing = references_removed - covered
        if missing:
            survivor_counterexamples.append({
                "survivor": survivor,
                "referencesRemoved": sorted(missing),
            })

    precursor_counterexamples: list[dict[str, object]] = []
    for tranche in tranches:
        tranche_number = tranche.get("tranche")
        package_members = {
            str(name) for name in tranche.get("package", [])
        }
        stories_by_test: dict[str, list[dict[str, object]]] = defaultdict(list)
        for story in tranche.get("precursorStories", []):
            if isinstance(story, dict) and story.get("kind") == "test-edit":
                stories_by_test[str(story.get("class", ""))].append(story)
        rewrites_by_test: dict[str, set[str]] = defaultdict(set)
        for unit in tranche.get("units", []):
            if not isinstance(unit, dict):
                continue
            for rewrite in unit.get("precursorRewrites", []):
                if not isinstance(rewrite, dict) or rewrite.get("kind") != "test-edit":
                    continue
                test = str(rewrite.get("class", ""))
                rewrites_by_test[test].update(
                    str(name) for name in rewrite.get("removeReferencesTo", [])
                )
        for test, removed_names in sorted(rewrites_by_test.items()):
            if test not in package_members:
                precursor_counterexamples.append({
                    "test": test,
                    "tranche": tranche_number,
                    "missing": "package.xml",
                })
            stories = stories_by_test.get(test, [])
            if not stories:
                precursor_counterexamples.append({
                    "test": test,
                    "tranche": tranche_number,
                    "missing": "precursor story",
                })
            elif len(stories) != 1:
                precursor_counterexamples.append({
                    "test": test,
                    "tranche": tranche_number,
                    "precursorStoryPlacements": len(stories),
                })
            else:
                story_removed = {
                    str(name)
                    for name in stories[0].get("removeReferencesTo", [])
                }
                if story_removed != removed_names:
                    precursor_counterexamples.append({
                        "test": test,
                        "tranche": tranche_number,
                        "storyRemovedReferences": sorted(story_removed),
                        "expectedRemovedReferences": sorted(removed_names),
                    })

    expected_manifests = [
        [
            str(name)
            for unit in tranche.get("units", [])
            for name in [*unit.get("members", []), *unit.get("tests", [])]
        ]
        for tranche in tranches
    ]
    manifest_counterexamples = [
        {
            "tranche": tranche.get("tranche"),
            "manifest": tranche.get("manifest", []),
            "expected": expected,
        }
        for tranche, expected in zip(tranches, expected_manifests)
        if tranche.get("manifest", []) != expected
    ]
    manifest_names = [name for manifest in expected_manifests for name in manifest]
    manifest_characters = sum(
        parse_int(
            catalog_by_name[name].get("countedCharacters", ""),
            allow_empty=True,
            field=f"{name} countedCharacters",
        ) or 0
        for name in manifest_names
        if name in catalog_by_name
    )
    forecast_total = sum(
        int(capacity_totals.get(key, 0) or 0)
        for key in ("forecastReconciled", "unreconciledCandidate")
    )
    capacity_counterexamples = list(manifest_counterexamples)
    if manifest_characters != forecast_total:
        capacity_counterexamples.append({
            "manifestCharacters": manifest_characters,
            "forecastCharacters": forecast_total,
        })
    realized = capacity_totals.get("confirmedRealized")
    if realized is not None and realized != manifest_characters:
        capacity_counterexamples.append({
            "manifestCharacters": manifest_characters,
            "confirmedRealized": realized,
        })

    return [
        {
            "name": "consumer-before-provider",
            "passed": not order_counterexamples,
            "counterexamples": order_counterexamples,
        },
        {
            "name": "test-attachments",
            "passed": not test_counterexamples,
            "counterexamples": test_counterexamples,
        },
        {
            "name": "survivor-references",
            "passed": not survivor_counterexamples,
            "counterexamples": survivor_counterexamples,
        },
        {
            "name": "test-edit-precursors",
            "passed": not precursor_counterexamples,
            "counterexamples": precursor_counterexamples,
        },
        {
            "name": "capacity",
            "passed": not capacity_counterexamples,
            "counterexamples": capacity_counterexamples,
        },
    ]


