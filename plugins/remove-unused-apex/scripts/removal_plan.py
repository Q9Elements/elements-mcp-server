    def story_text(title: str, members: list[str], tests: list[str], characters: int,
                   plan_record: dict[str, object] | None, extra_evidence: str,
                   behavior_impact: str, blockers: list[str] | None = None,
                   pending_rewrites: list[dict[str, object]] | None = None) -> str:
        identities = [f"- {name}: Salesforce Id `{catalog_by_name[name]['sfId']}`" for name in members if name in catalog_by_name]
        identities.extend(f"- Test: {name}: Salesforce Id `{catalog_by_name[name]['sfId']}`" for name in tests if name in catalog_by_name)
        zero = ", ".join(tests) or "None"
        evidence_lines = []
        for name in members:
            row = reasoned_by_name.get(name)
            if row:
                meanings = [reason_meanings.get(reason, reason.replace("_", " ")) for reason in row["reasons"].split(";") if reason]
                confidence = "high" if row["confidence"].casefold().startswith("high") else "medium"
                evidence_lines.append(
                    f"- {name}: Evidence: {verdict_wording.get(row['verdict'], verdict_wording['unknown'])} "
                    f"(confidence {confidence}). Reasons for doubt: {'; '.join(meanings) or 'none'}. "
                    f"Supporting evidence: {row['quotes'] or 'none'}."
                )
            else:
                evidence_lines.append(f"- {name}: no reasoned-candidates row available")
        evidence_lines.append(f"- Additional evidence: {extra_evidence}")
        cluster_details = {
            modification_cluster[name]
            for name in members
            if name in modification_cluster
        }
        for count, component, minute in sorted(cluster_details, key=lambda value: (value[1], value[2])):
            evidence_lines.append(
                f"- Modification cluster: {count} component members share lastModifiedDate minute "
                f"{minute} in {component}; this is treated as one deployment event."
            )
        if telemetry_ledger:
            evidence_lines.append(f"- Telemetry window: {telemetry_ledger.get('windowStart', 'unknown')} through {telemetry_ledger.get('windowEnd', 'unknown')}")
        else:
            evidence_lines.append("- Telemetry window: unavailable; telemetry-ledger.json was not present beside candidates.csv")
        absent_telemetry = absent_telemetry_result()
        if absent_telemetry:
            evidence_lines.append(f"- {absent_telemetry}")
        if args.string_holders:
            evidence_lines.extend(
                f"- {targeted_string_result(name)}" for name in members
            )
        if blind_spots:
            rendered_blind_spots = []
            for key in sorted(blind_spots):
                value = blind_spots[key]
                rendered_value = render_blind_spot_value(value)
                rendered_blind_spots.append(
                    f"{BLIND_SPOT_DISPLAY_NAMES.get(key, key)}: {rendered_value}"
                )
